#!/usr/bin/env python3
"""Manage per-file sidecar settings via a CSV table.

Workflow (bulk editing in Excel/Numbers/LibreOffice):

1. Generate a template with one row per audio file (existing sidecar values
   are pre-filled, so this is also an export of the current state)::

       python sidecar_tools.py template                 # curated columns
       python sidecar_tools.py template --all           # every allowed key
       python sidecar_tools.py template --out my.csv

2. Edit the CSV: fill in values only where a file needs to deviate from the
   global configuration. Leave cells empty to use global settings.

3. Write the sidecar files::

       python sidecar_tools.py apply swhisper_settings.csv
       python sidecar_tools.py apply my.csv --dry-run   # preview first
       python sidecar_tools.py apply my.csv --prune     # delete sidecars for all-empty rows

Other commands::

       python sidecar_tools.py list-keys                # allowed keys + types

The audio directory defaults to SWHISPER_AUDIO_DIR from .swhisper.env;
override with --audio-dir.
"""

from __future__ import annotations

import argparse
import csv
import os
import sys
from typing import Dict, List, Optional

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from path_settings import get_path_settings
from sidecar import (
    BLOCKED_KEYS,
    SIDECAR_PARAMS,
    SIDECAR_SUFFIX,
    parse_sidecar_file,
)

AUDIO_EXTENSIONS = {'.wav', '.m4a', '.mp3', '.mov', '.mp4', '.flac', '.aac', '.ogg'}

DEFAULT_CSV_NAME = "swhisper_settings.csv"

# Columns offered by default in the template (the common per-file needs).
CURATED_KEYS = [
    "SWHISPER_NUM_SPEAKERS",
    "SWHISPER_MIN_SPEAKERS",
    "SWHISPER_MAX_SPEAKERS",
    "SWHISPER_LANGUAGE",
    "SWHISPER_INITIAL_PROMPT",
    "SWHISPER_BACKFILL_ENABLED",
    "SWHISPER_BACKFILL_IGNORE_WORDS",
    "SWHISPER_INCLUDE_SILENCE",
    "SWHISPER_FORCE_REPROCESS",
    "SWHISPER_DIARIZE_FORCE_REPROCESS",
]

GENERATED_HEADER = "# Generated by sidecar_tools.py — per-file overrides for swhisper"


def _default_audio_dir() -> Optional[str]:
    settings = get_path_settings()
    return str(settings.audio_dir) if settings.audio_dir else None


def _resolve_audio_dir(arg_value: Optional[str]) -> str:
    audio_dir = arg_value or _default_audio_dir()
    if not audio_dir:
        sys.exit("❌ No audio directory. Pass --audio-dir or set SWHISPER_AUDIO_DIR in .swhisper.env")
    if not os.path.isdir(audio_dir):
        sys.exit(f"❌ Audio directory not found: {audio_dir}")
    return audio_dir


def _find_audio_basenames(audio_dir: str) -> List[str]:
    basenames = []
    for name in sorted(os.listdir(audio_dir)):
        base, ext = os.path.splitext(name)
        if ext.lower() in AUDIO_EXTENSIONS:
            if base not in basenames:
                basenames.append(base)
    return basenames


def _sidecar_path(audio_dir: str, basename: str) -> str:
    return os.path.join(audio_dir, basename + SIDECAR_SUFFIX)


def _load_existing_sidecars(audio_dir: str, basenames: List[str]) -> Dict[str, Dict[str, str]]:
    existing: Dict[str, Dict[str, str]] = {}
    for base in basenames:
        path = _sidecar_path(audio_dir, base)
        if os.path.isfile(path):
            existing[base] = parse_sidecar_file(path)
    # Also pick up sidecars whose audio file is not (currently) present
    for name in sorted(os.listdir(audio_dir)):
        if name.endswith(SIDECAR_SUFFIX):
            base = name[: -len(SIDECAR_SUFFIX)]
            if base not in existing and base not in basenames:
                existing[base] = parse_sidecar_file(os.path.join(audio_dir, name))
    return existing


def _csv_escape_for_sidecar(value: str) -> str:
    """Render a CSV cell value as a sidecar file value."""
    value = value.replace('\n', '\\n').replace('\t', '\\t').replace('\r', '\\r')
    if '#' in value or value != value.strip():
        return f'"{value}"'
    return value


def cmd_list_keys(_args: argparse.Namespace) -> None:
    print(f"{'KEY':<42} {'STAGE':<11} NOTE")
    print("-" * 80)
    for key, param in SIDECAR_PARAMS.items():
        print(f"{key:<42} {param.stage:<11} {param.note}")
    print(f"\n{len(SIDECAR_PARAMS)} keys allowed in sidecar files.")
    print("Values use the same syntax as .swhisper.env (booleans: true/false, lists: comma-separated).")


def cmd_template(args: argparse.Namespace) -> None:
    audio_dir = _resolve_audio_dir(args.audio_dir)
    basenames = _find_audio_basenames(audio_dir)
    if not basenames:
        print(f"⚠️ No audio files found in {audio_dir}")
    existing = _load_existing_sidecars(audio_dir, basenames)

    keys = list(SIDECAR_PARAMS.keys()) if args.all else list(CURATED_KEYS)
    # Ensure keys already used in existing sidecars are included
    for values in existing.values():
        for key in values:
            if key in SIDECAR_PARAMS and key not in keys:
                keys.append(key)

    all_rows = basenames + [b for b in existing if b not in basenames]
    out_path = args.out or os.path.join(audio_dir, DEFAULT_CSV_NAME)

    with open(out_path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["file"] + keys)
        for base in all_rows:
            values = existing.get(base, {})
            writer.writerow([base] + [values.get(k, "") for k in keys])

    print(f"✅ Template written: {out_path}")
    print(f"   {len(all_rows)} rows ({len(existing)} with existing sidecar values), {len(keys)} setting columns.")
    print("   Fill in cells only where a file should deviate from the global config,")
    print(f"   then run: python sidecar_tools.py apply {out_path}")


def cmd_apply(args: argparse.Namespace) -> None:
    audio_dir = _resolve_audio_dir(args.audio_dir)
    csv_path = args.csv
    if not os.path.isfile(csv_path):
        sys.exit(f"❌ CSV file not found: {csv_path}")

    with open(csv_path, newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        if not reader.fieldnames or "file" not in reader.fieldnames:
            sys.exit("❌ CSV must have a 'file' column (audio file basename, without extension).")

        # Validate columns once
        setting_cols = [c for c in reader.fieldnames if c != "file"]
        valid_cols = []
        for col in setting_cols:
            if col in SIDECAR_PARAMS:
                valid_cols.append(col)
            elif col in BLOCKED_KEYS:
                print(f"⚠️ Column '{col}' is not allowed per file ({BLOCKED_KEYS[col]}) — ignored")
            else:
                print(f"⚠️ Unknown column '{col}' — ignored")

        written = skipped = pruned = errors = 0
        for row in reader:
            base = (row.get("file") or "").strip()
            if not base:
                continue
            base = os.path.splitext(base)[0] if os.path.splitext(base)[1].lower() in AUDIO_EXTENSIONS else base

            values = {}
            for col in valid_cols:
                raw = (row.get(col) or "").strip()
                if not raw:
                    continue
                try:
                    SIDECAR_PARAMS[col].parse(raw)  # validate only
                except (ValueError, TypeError) as exc:
                    print(f"❌ {base}: invalid value {col}={raw!r} ({exc}) — row skipped")
                    errors += 1
                    values = None
                    break
                values[col] = raw
            if values is None:
                continue

            path = _sidecar_path(audio_dir, base)
            if not values:
                if os.path.isfile(path):
                    if args.prune:
                        if not args.dry_run:
                            os.remove(path)
                        print(f"🗑  {base}: sidecar removed (empty row + --prune)")
                        pruned += 1
                    else:
                        print(f"⏩ {base}: row empty, existing sidecar left untouched (use --prune to delete)")
                        skipped += 1
                continue

            lines = [GENERATED_HEADER, f"# Source: {os.path.basename(csv_path)}", ""]
            lines += [f"{k}={_csv_escape_for_sidecar(v)}" for k, v in values.items()]
            content = "\n".join(lines) + "\n"

            if args.dry_run:
                print(f"—— {base}{SIDECAR_SUFFIX} (dry run) " + "—" * 20)
                print(content, end="")
            else:
                with open(path, "w", encoding="utf-8") as out:
                    out.write(content)
                print(f"✅ {base}{SIDECAR_SUFFIX}: {len(values)} setting(s)")
            written += 1

    action = "Would write" if args.dry_run else "Wrote"
    print(f"\n{action} {written} sidecar file(s); {skipped} untouched, {pruned} pruned, {errors} row error(s).")
    if not args.dry_run and written:
        print("Note: sidecars newer than existing outputs trigger reprocessing of the affected files on the next run.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    p_list = sub.add_parser("list-keys", help="List settings allowed in sidecar files")
    p_list.set_defaults(func=cmd_list_keys)

    p_tmpl = sub.add_parser("template", help="Generate a CSV template (pre-filled from existing sidecars)")
    p_tmpl.add_argument("--audio-dir", help="Audio directory (default: SWHISPER_AUDIO_DIR)")
    p_tmpl.add_argument("--out", help=f"Output CSV path (default: <audio-dir>/{DEFAULT_CSV_NAME})")
    p_tmpl.add_argument("--all", action="store_true", help="Include a column for every allowed key")
    p_tmpl.set_defaults(func=cmd_template)

    p_apply = sub.add_parser("apply", help="Write sidecar files from a CSV table")
    p_apply.add_argument("csv", help="CSV file (as produced by 'template')")
    p_apply.add_argument("--audio-dir", help="Audio directory (default: SWHISPER_AUDIO_DIR)")
    p_apply.add_argument("--dry-run", action="store_true", help="Show what would be written without writing")
    p_apply.add_argument("--prune", action="store_true", help="Delete sidecars for rows with no values")
    p_apply.set_defaults(func=cmd_apply)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
